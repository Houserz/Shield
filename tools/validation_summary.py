#!/usr/bin/env python3
"""
validation_summary.py -- turn the validated sessions into the numbers that fill
the [INPUT] placeholders in the section 3.7 paragraphs (C-03, C-04) and C-12.

It reuses validate_sessions.check_session (same folder), so the pass/fail logic
is the validator's, and adds what the validator does not print: per-board
counts, SD self-test attempts from meta.json, the BNO085 read-back block, and
(optionally) the ADS1115 timeout / I2C error counts from the driver's CSV.

Usage (repo root, PowerShell):
  python tools\\validation_summary.py D:\\ E:\\ --runs RUN_003,RUN_004 --csv validation_2026-10-08_sessions.csv --out validation_summary.md

Writes a Markdown file and prints it. Nothing here is estimated: a value that
is not in the files is printed as "not recorded".
"""
import argparse
import csv
import json
import os
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import validate_sessions as vs  # noqa: E402


def load_meta(run_dir):
    try:
        with open(os.path.join(run_dir, "meta.json")) as f:
            return json.load(f)
    except Exception:  # noqa
        return {}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("roots", nargs="+")
    ap.add_argument("--runs", help="comma-separated RUN_xxx names (as printed by bench_validate_run.py)")
    ap.add_argument("--csv", help="the *_sessions.csv written by bench_validate_run.py")
    ap.add_argument("--min-duration-min", type=float, default=20.0)
    ap.add_argument("--out", default="validation_summary.md")
    args = ap.parse_args()
    vs.MIN_DURATION_S = args.min_duration_min * 60.0
    wanted = {x.strip() for x in args.runs.split(",")} if args.runs else None

    runs = []
    for root in args.roots:
        for name in sorted(os.listdir(root)):
            p = os.path.join(root, name)
            if name.startswith("RUN_") and os.path.isdir(p) and (wanted is None or name in wanted):
                runs.append(p)
    if not runs:
        sys.exit("no RUN_xxx folders found")

    rows = []
    for p in runs:
        r = vs.check_session(p)
        meta = load_meta(p)
        dev = meta.get("device_info", {})
        r["selftest_attempts"] = dev.get("sd_selftest_attempts")
        r["bno085"] = meta.get("bno085", {})
        r["root"] = os.path.dirname(p)
        rows.append(r)

    n = len(rows)
    n_pass = sum(1 for r in rows if r["pass"])
    n_tiers = sum(1 for r in rows if all(v > 0 for v in r["sizes"].values()))
    g = [r["g011_related_fraction"] for r in rows if r["g011_related_fraction"] is not None]
    by_board = defaultdict(list)
    for r in rows:
        by_board[r["board_mac"] or "not recorded"].append(r)
    remount = [r for r in rows if (r["selftest_attempts"] or 0) > 1]
    hashes = sorted({str(r["firmware_git"]) for r in rows})
    ticks = sorted({str(r["tick_hz"]) for r in rows})
    markers = sum((r["markers_in_log"] or 0) for r in rows)
    rtc = sum(1 for r in rows if r["rtc_set"])

    ads_to = ads_ie = None
    if args.csv and os.path.isfile(args.csv):
        with open(args.csv, newline="", encoding="utf-8") as f:
            cr = [x for x in csv.DictReader(f) if (not wanted or x["run_id"] in wanted or not x["run_id"])]
        try:
            ads_to = sum(int(x["ads_timeouts"]) for x in cr if x["ads_timeouts"] != "")
            ads_ie = sum(int(x["ads_i2c_err"]) for x in cr if x["ads_i2c_err"] != "")
        except ValueError:
            pass

    L = []
    L.append("# Validation summary (C-12)\n")
    L.append("Generated by `tools/validation_summary.py` from the card files. Values copy straight into the C-03 / C-04 placeholders.\n")
    L.append("## Result\n")
    L.append(f"- Sessions checked: **{n}**; passing the validator: **{n_pass}**; with all three tier files non-empty: **{n_tiers}**.")
    L.append(f"- Firmware git hash(es) in `meta.json`: {', '.join(hashes)}; FreeRTOS tick (Hz): {', '.join(ticks)}.")
    L.append(f"- Boards seen (MAC): {', '.join(by_board)}.  Sessions per board: "
             + ", ".join(f"{m}: {len(v)}" for m, v in by_board.items()) + ".")
    L.append(f"- Sessions needing an SD remount at boot (self-test attempts > 1): **{len(remount)}**"
             + (" (" + ", ".join(f"{r['run']} on {r['board_mac']}, attempts {r['selftest_attempts']}" for r in remount) + ")" if remount else "") + ".")
    L.append(f"- G0.11 related fraction, maximum over the sessions: **{max(g):.4f}**" if g else "- G0.11: not recorded.")
    L.append(f"  (the validator's limit is 0.05; the released Tier 2 corpus is about 1.0)")
    L.append(f"- Converter conversion timeouts: **{ads_to if ads_to is not None else 'not recorded (pass --csv)'}**; I2C errors: **{ads_ie if ads_ie is not None else 'not recorded (pass --csv)'}**.")
    L.append(f"- Marker lines in events.log: {markers}; sessions with the RTC set: {rtc} of {n}.")
    L.append("\n## Per session\n")
    L.append("| run | board MAC | pass | duration s | G0.11 | self-test attempts | markers | reasons |")
    L.append("|---|---|---|---|---|---|---|---|")
    for r in rows:
        gf = f"{r['g011_related_fraction']:.4f}" if r["g011_related_fraction"] is not None else "n/a"
        L.append(f"| {r['run']} | {r['board_mac']} | {'OK' if r['pass'] else 'FAIL'} | {r['duration_s']:.0f} | {gf} | "
                 f"{r['selftest_attempts']} | {r['markers_in_log']} | {'; '.join(r['reasons'])} |")
    L.append("\n## BNO085 read-back as written by the firmware (first session of each board)\n")
    seen = set()
    for r in rows:
        if r["board_mac"] in seen:
            continue
        seen.add(r["board_mac"])
        L.append(f"- {r['board_mac']} ({r['run']}): `{json.dumps(r['bno085'])}`")
    L.append("\nThis firmware records the calibration bitmask (1 accel, 2 gyro, 4 mag, 8 planar) and the report names and "
             "intervals. It does not read per-sensor range, resolution or the accuracy status.")
    text = "\n".join(L) + "\n"
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(text)
    print(text)
    sys.exit(0 if n_pass == n else 1)


if __name__ == "__main__":
    main()
